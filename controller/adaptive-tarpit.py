class Error(Exception):
    pass


def validate_ip(ip):
    """Accept only a literal dotted-quad IPv4 address; reject IPv6, CIDR and ranges.

    Ranges are never published (FLEET-STATE.md §5): a /24 claim would quarantine every
    address in it on one host's opinion, and Apache's `txt:` map has no prefix semantics -
    it matches the literal string, so a CIDR written into the map would quarantine nothing.

    Two anchor/character-class details are load-bearing, both found by
    tests/security/test_input_hardening.py:
      * `\\A...\\Z` instead of `^...$`, because `$` also matches before a trailing newline, so
        `"1.2.3.4\\n"` used to be stored and rendered as an extra line in the Apache map;
      * `[0-9]` instead of `\\d`, because `\\d` is Unicode-aware in Python 3, so `1.2.3.٤`
        matched and `int("٤")` satisfied the octet check.
    """
    match = IPV4.match(ip)
    if not match:
        raise Error("not a valid IPv4 address (v1 does not accept IPv6 or CIDR): %r" % ip)
    for octet in match.groups():
        if int(octet) > 255:
            raise Error("not a valid IPv4 address: %r" % ip)
    if "/" in ip:
        raise Error("ranges are never published, only exact /32s (FLEET-STATE.md section 5): %r" % ip)
    return ip


def now():
    """Single clock source for the store.

    Callers capture this once per operation and reuse it, so a claim's `created_at` and
    `expires_at` can never disagree by a second across two calls (that race made TTL
    assertions flaky until it was removed).
    """
    return int(time.time())


class Store(object):
    """Authoritative claim store.

    PT-05 - claims are keyed by ``(ip, claim_key)``, not by ``ip`` alone. One address can
    legitimately hold independent opinions from Wazuh, fail2ban, an inline signature and
    another fleet host; collapsing them onto one row meant a weaker verdict overwrote a
    stronger one and revoking one opinion discarded the others. The effective verdict for
    an address is derived from all of its unexpired claims, strongest first.

    PT-01 - ``authoritative`` distinguishes "the store was read successfully and holds
    zero claims" from "the store could not be read". Only the latter may block a render;
    conflating them is what left an expired last lease stuck in the Apache map.

    Read-only commands (`list`, `verify`) open the database in `mode=ro` so a non-root
    operator can inspect state without sudo (the store uses journal_mode=DELETE so no
    unwritable `-shm` file is involved).
    """

    def __init__(self, path, readonly=False):
        """Open the claim store: create/migrate the schema when writable, detect it when not.

        `readonly=True` never writes and never migrates (a non-root operator can inspect
        state without sudo). `readonly=False` opens read-write and may run the v1 -> v2
        migration. A missing path under `readonly` is not an error - it means "no state
        yet", which `authoritative` reports honestly.
        """
        self.path = path
        self.readonly = readonly
        self.migrated_from = None
        if readonly:
            self.conn = None if not os.path.exists(path) else self._open_ro(path)
            self.schema = self._detect_schema() if self.conn is not None else None
            return
        directory = os.path.dirname(os.path.abspath(path))
        if directory and not os.path.isdir(directory):
            try:
                os.makedirs(directory, mode=0o755)
            except OSError as exc:
                raise Error("cannot create %s: %s" % (directory, exc))
        try:
            self.conn = sqlite3.connect(path, timeout=5)
            # Rollback journal, not WAL. Journal mode is persistent in the db header, so this
            # also converts a db that was previously created in WAL. WAL would let `list` run
            # without root only if the -shm/-wal files were also readable, which they are not
            # once root owns the directory; the store is small and single-writer, so WAL buys
            # nothing here and costs non-root visibility.
            self.conn.execute("PRAGMA journal_mode=DELETE")
        except sqlite3.Error as exc:
            raise Error("cannot open %s for writing (running as uid %d?): %s" % (path, os.getuid(), exc))
        self._ensure_schema()

    def _detect_schema(self):
        """Read-only opens cannot migrate, so they must read whichever table exists."""
        for table in ("claims", "leases", "leases_v1_backup"):
            if self.conn.execute(
                "SELECT name FROM sqlite_master WHERE type='table' AND name = ?", (table,)
            ).fetchone():
                return table
        return None

    @staticmethod
    def _open_ro(path):
        """Open an existing db through a `mode=ro` URI so a read cannot create a file or
        require write permission (a plain connect() on a read-only file raises)."""
        try:
            return sqlite3.connect("file:%s?mode=ro" % path, uri=True, timeout=5)
        except sqlite3.Error as exc:
            raise Error("cannot open %s read-only: %s" % (path, exc))

    @property
    def authoritative(self):
        """False only when the store could not be opened at all (PT-01)."""
        return self.conn is not None

    @property
    def schema(self):
        """The table this store actually reads: `claims` (v2) or the legacy `leases` (v1)."""
        return getattr(self, "_schema", "claims")

    @schema.setter
    def schema(self, value):
        """Backing store for the `schema` property; set during open/detect only."""
        self._schema = value

    def _ensure_schema(self):
        """Create the v2 `claims` table and migrate a v1 `leases` table into it."""
        self.conn.execute(
            """CREATE TABLE IF NOT EXISTS claims (
                   ip          TEXT NOT NULL,
                   claim_key   TEXT NOT NULL,
                   verdict     TEXT NOT NULL,
                   source      TEXT,
                   author      TEXT,
                   created_at  INTEGER NOT NULL,
                   expires_at  INTEGER NOT NULL,
                   PRIMARY KEY (ip, claim_key)
               )"""
        )
        # H4: the ladder history outlives the leases it produced. `claims` rows are deleted when
        # leases expire, so without this table the controller could not tell a first-time suspect
        # from a fourth one, and the 15m -> 30m -> 60m -> drop ladder would always hand out 15m.
        self.conn.execute(
            """CREATE TABLE IF NOT EXISTS ladder (
                   ip             TEXT PRIMARY KEY,
                   claims         INTEGER NOT NULL,
                   last_claim_at  INTEGER NOT NULL,
                   rung           TEXT NOT NULL
               )"""
        )
        self.conn.commit()
        legacy = self.conn.execute(
            "SELECT name FROM sqlite_master WHERE type='table' AND name='leases'"
        ).fetchone()
        if not legacy:
            return
        # v1 schema: one row per ip. Carry each row across under the identity it recorded
        # so a Wazuh claim and a fail2ban claim do not collapse into one during migration.
        rows = self.conn.execute(
            "SELECT ip, verdict, source, author, created_at, expires_at FROM leases"
        ).fetchall()
        moved = 0
        for ip, verdict, source, author, created_at, expires_at in rows:
            if verdict not in VERDICT_RANK:
                continue
            try:
                self.conn.execute(
                    "INSERT OR IGNORE INTO claims"
                    " (ip, claim_key, verdict, source, author, created_at, expires_at)"
                    " VALUES (?,?,?,?,?,?,?)",
                    (ip, source or author or "legacy-v1", verdict, source, author, created_at, expires_at),
                )
                moved += 1
            except sqlite3.Error:
                continue
        self.conn.execute("ALTER TABLE leases RENAME TO leases_v1_backup")
        self.conn.commit()
        self.migrated_from = "leases_v1_backup (%d rows)" % moved

    def claim(self, ip, verdict, source=None, author=None, ttl=None, claim_key=None):
        """Record one source's opinion. Returns added | extended | promoted | revived | unchanged.

        PT-05: a repeat claim from the *same* identity extends the lease and may strengthen
        the verdict, but a weaker verdict never replaces a stronger active one.

        PTN-09: `revived` is the expired-row case. An expired claim is a finished fact, not a
        standing verdict, so it is replaced by the new claim instead of being compared with it.
        """
        if self.readonly:
            raise Error("store %s was opened read-only" % self.path)
        validate_ip(ip)
        if verdict not in DEFAULT_TTL:
            raise Error("verdict must be one of %s" % ", ".join(sorted(DEFAULT_TTL)))
        ttl = DEFAULT_TTL[verdict] if ttl is None else int(ttl)
        key = claim_key or source or author or "manual"
        moment = now()
        wanted = moment + ttl
        row = self.conn.execute(
            "SELECT verdict, expires_at FROM claims WHERE ip = ? AND claim_key = ?", (ip, key)
        ).fetchone()
        if row:
            current_verdict, current_expiry = row
            if current_expiry <= moment:
                # PTN-09: the row exists but its lease had already lapsed. The code below compares
                # against, or extends, a verdict that is no longer in force, so a fresh `suspect`
                # observation renewed an expired `confirmed` quarantine and kept the `confirmed`
                # label - the address stayed quarantined on evidence that had expired. Isolated
                # repro from the review: insert an expired confirmed row, `active()` is empty, claim
                # a suspect with the same identity, and the store reported it confirmed. An expired
                # claim is now replaced outright: verdict, provenance, and window all come from the
                # new observation, which is what `active()` will be reporting.
                self.conn.execute(
                    "UPDATE claims SET verdict = ?, source = ?, author = ?, created_at = ?,"
                    " expires_at = ? WHERE ip = ? AND claim_key = ?",
                    (verdict, source, author, moment, wanted, ip, key),
                )
                self.conn.commit()
                return "revived"
            if VERDICT_RANK[verdict] > VERDICT_RANK[current_verdict]:
                # Promotion: the stronger verdict's own TTL defines the new expiry.
                self.conn.execute(
                    "UPDATE claims SET verdict = ?, expires_at = ? WHERE ip = ? AND claim_key = ?",
                    (verdict, wanted, ip, key),
                )
                self.conn.commit()
                return "promoted"
            if current_expiry >= wanted:
                return "unchanged"
            self.conn.execute(
                "UPDATE claims SET expires_at = ? WHERE ip = ? AND claim_key = ?", (wanted, ip, key)
            )
            self.conn.commit()
            return "extended"
        self.conn.execute(
            "INSERT INTO claims"
            " (ip, claim_key, verdict, source, author, created_at, expires_at) VALUES (?,?,?,?,?,?,?)",
            (ip, key, verdict, source, author, moment, wanted),
        )
        self.conn.commit()
        return "added"

    def revoke(self, ip, claim_key=None):
        """Remove one claim, or every claim for the address when claim_key is omitted."""
        validate_ip(ip)
        if claim_key:
            cur = self.conn.execute("DELETE FROM claims WHERE ip = ? AND claim_key = ?", (ip, claim_key))
        else:
            cur = self.conn.execute("DELETE FROM claims WHERE ip = ?", (ip,))
        self.conn.commit()
        return cur.rowcount > 0

    def ladder_state(self, ip):
        """Return the H4 ladder row for an address as a dict, or None if it was never claimed."""
        row = self.conn.execute(
            "SELECT ip, claims, last_claim_at, rung FROM ladder WHERE ip = ?", (ip,)
        ).fetchone()
        if row is None:
            return None
        return {"ip": row[0], "claims": row[1], "last_claim_at": row[2], "rung": row[3]}

    def record_ladder(self, ip, rung, at=None):
        """Record one more observation of an address and the rung its claim earned; returns the count.

        Kept apart from `claims` on purpose: lease rows are deleted when they expire, so the running
        total has to live somewhere that is not purged, otherwise every address looks new again after
        its lease lapses and the ladder can never escalate past its first rung.
        """
        if self.readonly:
            raise Error("store %s was opened read-only" % (self.path,))
        validate_ip(ip)
        moment = now() if at is None else int(at)
        current = self.ladder_state(ip)
        claims = 1 if current is None else current["claims"] + 1
        # UPDATE-then-INSERT rather than INSERT ... ON CONFLICT: the latter needs SQLite 3.24 and the
        # oldest managed host still runs the interpreter that shipped with its distro.
        cursor = self.conn.execute(
            "UPDATE ladder SET claims = ?, last_claim_at = ?, rung = ? WHERE ip = ?",
            (claims, moment, rung, ip),
        )
        if cursor.rowcount == 0:
            self.conn.execute(
                "INSERT INTO ladder (ip, claims, last_claim_at, rung) VALUES (?,?,?,?)",
                (ip, claims, moment, rung),
            )
        self.conn.commit()
        return claims

    def claims(self, at=None):
        """Every unexpired claim row, from whichever schema version is present.

        v2 returns one row per `(ip, claim_key)`; v1 returns one row per ip with an
        implicit `claim_key`, so both layouts present the same shape to every caller and
        no caller needs to know which schema it is reading.
        """
        at = now() if at is None else at
        if self.conn is None or self.schema is None:
            return []
        if self.schema == "claims":
            rows = self.conn.execute(
                "SELECT ip, claim_key, verdict, source, author, created_at, expires_at FROM claims "
                "WHERE expires_at > ? ORDER BY ip, claim_key",
                (at,),
            ).fetchall()
            return [dict(zip(("ip", "claim_key", "verdict", "source", "author", "created_at", "expires_at"), r))
                    for r in rows]
        # v1 layout (one row per ip) - read it as a single implicit claim per address.
        rows = self.conn.execute(
            "SELECT ip, COALESCE(source, author, 'legacy-v1'), verdict, source, author, "
            "created_at, expires_at FROM leases WHERE expires_at > ? ORDER BY ip",
            (at,),
        ).fetchall()
        return [dict(zip(("ip", "claim_key", "verdict", "source", "author", "created_at", "expires_at"), r))
                for r in rows]

    def active(self, at=None):
        """Effective state per address, derived from every unexpired claim (PT-05)."""
        at = now() if at is None else at
        grouped = {}
        for claim in self.claims(at):
            entry = grouped.get(claim["ip"])
            if entry is None:
                grouped[claim["ip"]] = {
                    "ip": claim["ip"],
                    "verdict": claim["verdict"],
                    "source": claim["source"],
                    "author": claim["author"],
                    "created_at": claim["created_at"],
                    "expires_at": claim["expires_at"],
                    "claims": 1,
                }
                continue
            entry["claims"] += 1
            entry["created_at"] = min(entry["created_at"], claim["created_at"])
            if VERDICT_RANK[claim["verdict"]] > VERDICT_RANK[entry["verdict"]]:
                entry["verdict"] = claim["verdict"]
                entry["source"] = claim["source"]
                entry["author"] = claim["author"]
                entry["expires_at"] = max(entry["expires_at"], claim["expires_at"])
            elif VERDICT_RANK[claim["verdict"]] == VERDICT_RANK[entry["verdict"]]:
                entry["expires_at"] = max(entry["expires_at"], claim["expires_at"])
        return sorted(grouped.values(), key=lambda e: (-e["expires_at"], e["ip"]))

    def claim_keys(self, at=None):
        """{(ip, claim_key)} currently under lease - used to keep ingest idempotent."""
        return {(c["ip"], c["claim_key"]) for c in self.claims(at)}

    def set_meta(self, key, value):
        """Persist render parameters so `verify` can reproduce an exact render."""
        if self.readonly:
            return
        self.conn.execute("CREATE TABLE IF NOT EXISTS meta (k TEXT PRIMARY KEY, v TEXT)")
        self.conn.execute("INSERT OR REPLACE INTO meta(k, v) VALUES(?, ?)", (key, str(value)))
        self.conn.commit()

    def get_meta(self, key, default=None):
        """Read a persisted render parameter (e.g. `last_max_tarpit`).

        Tolerates a pre-meta store and a read-only open by returning `default` instead of
        raising - `verify` must still work against an old database.
        """
        if self.conn is None:
            return default
        try:
            row = self.conn.execute("SELECT v FROM meta WHERE k = ?", (key,)).fetchone()
        except sqlite3.Error:  # no meta table yet (pre-meta store)
            return default
        return row[0] if row else default

    def expired_ips(self, at=None):
        """Addresses holding at least one claim whose TTL has passed (what `purge_expired` deletes).

        `claims()` deliberately returns only live rows, so the set about to be deleted has to be read
        separately; the E13 audit record names them because "which leases lapsed" is the question an
        operator or Wazuh asks after the fact.
        """
        at = now() if at is None else at
        if self.conn is None or self.schema is None:
            return []
        return [row[0] for row in self.conn.execute(
            "SELECT DISTINCT ip FROM claims WHERE expires_at <= ? ORDER BY ip", (at,)).fetchall()]


    def purge_expired(self, at=None):
        """Delete claims whose `expires_at` has passed; return how many rows were removed.

        Deletion is what makes the render authoritative: the row's absence *is* the state
        change, so this must run before a render that claims to reflect the store.
        """
        at = now() if at is None else at
        cur = self.conn.execute("DELETE FROM claims WHERE expires_at <= ?", (at,))
        self.conn.commit()
        return cur.rowcount


def unwrap_alert(obj):
    """PT-02 - return ``(command, alert)`` for either Wazuh wire format.

    Wazuh 4.x active response hands the script an envelope::

        {"version":1,"origin":{...},"command":"add",
         "parameters":{"extra_args":[],"alert":{...},"program":"..."}}

    The alert we care about is ``parameters.alert``; the raw alert object (Wazuh API
    poller, fleet claim, our own test fixtures) has no ``parameters`` wrapper. Passing a
    4.x envelope in as if it were an alert used to fail with "no source address in alert".
    """
    if isinstance(obj, dict) and isinstance(obj.get("parameters"), dict) and "alert" in obj["parameters"]:
        return str(obj.get("command") or "add").lower(), obj["parameters"]["alert"]
    return None, obj


def parse_wazuh_alert(alert):
    """
    Normalise a Wazuh alert object into a verdict.

    The field names differ between rule families (`data.srcip` for web/auth, occasionally
    a list), so this accepts the variants rather than betting on one, and falls back to
    the client address in `full_log` (Apache combined format) when `data` is absent.
    """
    if not isinstance(alert, dict):
        raise Error("alert payload is not a JSON object")
    rule = alert.get("rule") or {}
    data = alert.get("data") or {}

    ip = None
    for key in ("srcip", "src_ip", "client_ip", "user_srcip"):
        value = data.get(key)
        if isinstance(value, list) and value:
            value = value[0]
        if isinstance(value, str) and value.strip():
            ip = value.strip()
            break
    if ip is None:
        # Apache combined log line: first whitespace-delimited field is the client address.
        full_log = alert.get("full_log")
        if isinstance(full_log, str) and full_log.strip():
            candidate = full_log.split()[0]
            if IPV4.match(candidate):
                ip = candidate
    if not ip:
        raise Error("no source address in alert (rule id %s)" % rule.get("id", "?"))

    level = rule.get("level")
    try:
        level = int(level) if level is not None else None
    except (TypeError, ValueError):
        level = None

    groups = rule.get("groups", rule.get("group", []))
    if isinstance(groups, str):
        groups = [groups]

    agent = alert.get("agent") or {}
    agent_id = agent.get("id") if isinstance(agent, dict) else None
    location = alert.get("location")
    if isinstance(location, list):  # multi-file alerts
        location = location[0] if location else None

    return {
        "ip": ip,
        "rule_id": str(rule.get("id", "")) or None,
        "level": level,
        "groups": [str(g) for g in groups] if isinstance(groups, list) else [str(groups)],
        "agent_id": str(agent_id) if agent_id is not None else None,
        "location": location,
        "description": rule.get("description"),
    }


def read_payload(args):
    """PT-02 - never block waiting for EOF on an AR pipe that stays open.

    Wazuh writes one newline-delimited JSON message per invocation and may keep the pipe
    open, so `sys.stdin.read()` can hang the response. Read the first line; only if it is
    not valid JSON (a pretty-printed payload) keep reading the rest.
    """
    if args.file != "-":
        try:
            with open(args.file) as handle:
                raw = handle.read()
        except IOError as exc:
            raise Error("cannot read payload %s: %s" % (args.file, exc))
    else:
        first = sys.stdin.readline()
        if not first.strip():
            raise Error("empty payload")
        try:
            json.loads(first)
            raw = first
        except ValueError:
            raw = first + sys.stdin.read()
    if not raw.strip():
        raise Error("empty payload%s" % ("" if args.file == "-" else " in %s" % args.file))
    return raw


def cmd_ingest(args):
    """
    Consume a verdict payload and record it. This is the single entry point every
    detection source funnels through - Wazuh active response today, the Wazuh API
    poller and fleet-claim sync later - so the sources stay thin and the store stays
    the only place state is written.
    """
    raw = read_payload(args)
    own_logs = set(args.own_log) if args.own_log else set(DEFAULT_OWN_LOGS)
    source_override = getattr(args, "source", None)
    author = args.author or (source_override.split("-")[0] if source_override else "wazuh")
    try:
        parsed = json.loads(raw)
    except ValueError as exc:
        raise Error("payload is not valid JSON: %s" % exc)
    alerts = parsed if isinstance(parsed, list) else [parsed]

    store = Store(args.db)
    if store.migrated_from:
        sys.stderr.write("note: migrated v1 store (%s)\n" % store.migrated_from)
    allowlist = load_allowlist(args.allowlist)
    confirm_rules = set(args.confirm_rule or DEFAULT_CONFIRM_RULES)
    changes = 0

    for item in alerts:
        command, alert = unwrap_alert(item)

        # PT-02: the AR handshake (`check_keys`, `continue`) is protocol chatter. Claiming
        # on it would invent a verdict the manager never made.
        if command in AR_HANDSHAKE_COMMANDS:
            print("skip       (protocol)     active-response command %s" % command)
            continue
        # PT-02: an unban must never turn into a new claim. Default policy is to ignore it,
        # because the controller timer is the only reaper (see the fail2ban action's
        # `actionunban = /bin/true`); `--on-delete revoke` opts into honouring it.
        if command in AR_REMOVE_COMMANDS:
            try:
                ip = parse_wazuh_alert(alert)["ip"]
            except Error:
                ip = "?"
            if args.on_delete == "revoke" and not args.dry_run:
                removed = store.revoke(ip)
                print("%-11s %-16s revoke requested by active response" % ("revoked" if removed else "absent", ip))
                if removed:
                    changes += 1
            else:
                print("skip       %-16s active-response %s ignored (leases age out via expire)"
                      % (ip, command))
            continue
        if command not in (None, "add"):
            print("skip       (unknown)      active-response command %s" % command)
            continue

        verdict_parsed = parse_wazuh_alert(alert)
        ip = verdict_parsed["ip"]
        source = source_override or "wazuh-rule-%s" % (verdict_parsed["rule_id"] or "unknown")
        claim_key = source

        # Loop prevention: our own tarpit responses get logged, Wazuh alerts on them, and
        # the AR would tell us to tarpit the client we are already tarpitting. Skip any
        # alert sourced from a log we generate ourselves.
        if own_logs and verdict_parsed["location"] in own_logs:
            print("skip       %-16s source log %s is our own" % (ip, verdict_parsed["location"]))
            continue
        if ip in allowlist:
            print("allowlist  %-16s not claimed" % ip)
            continue
        if args.expect_agent_id and verdict_parsed["agent_id"] not in (None, args.expect_agent_id):
            raise Error(
                "alert is about agent %s, not %s - refusing to act on another host's alert"
                % (verdict_parsed["agent_id"], args.expect_agent_id)
            )

        # PT-09: severity is not evidence. `confirmed` comes from an explicit --verdict or
        # from a rule id whose contract says so; everything else is suspect.
        if args.verdict:
            verdict = args.verdict
        elif verdict_parsed["rule_id"] in confirm_rules:
            verdict = "confirmed"
        elif args.confirm_by_level and verdict_parsed["level"] is not None:
            verdict = "confirmed" if verdict_parsed["level"] >= args.confirm_level else "suspect"
        else:
            verdict = "suspect"

        # PT-05: idempotency is per claim, not per address - a second source reporting the
        # same address is new information, not a duplicate. `claim()` decides whether this
        # is an add, an extension, a promotion, or a genuine no-op.
        if args.dry_run:
            print("would claim %-16s %s (%s)" % (ip, verdict, source))
            changes += 1
            continue
        result = store.claim(ip, verdict, source, author=author, ttl=args.ttl, claim_key=claim_key)
        print("%-11s %-16s %s (%s)" % (result, ip, verdict, source))
        if result != "unchanged":
            changes += 1

    if args.render and not args.dry_run and changes:
        do_render(store, args)
    return 0


def load_allowlist(path):
    """Local allowlist wins over every verdict, local or remote (DETECTION-INPUTS.md section 6)."""
    if not os.path.exists(path):
        return set()
    entries = set()
    with open(path) as handle:
        for line in handle:
            line = line.split("#", 1)[0].strip()
            if line:
                entries.add(line)
    return entries


def emit_audit(args, event, **fields):
    """E13: append one structured event to the controller audit log.

    The contract with Wazuh (docs/spec/DETECTION-INPUTS.md section 1) is that Path A - the deterministic
    exploit-signature path - becomes visible to Path B - the probabilistic behavioural path. That only
    works if the record is machine-parseable without a bespoke decoder, so each line is one complete
    JSON object: a schema version, a UTC timestamp, the acting host, the event name, and the fields
    Wazuh correlates on (address, verdict, signature/source, resulting map value).

    A write failure is a loud warning rather than a failed command. The state change has already
    committed at this point, and turning a successful claim into a non-zero exit because a *log* could
    not be written would leave the caller unable to tell whether the claim exists. Losing the feed is
    still serious, so it goes to stderr on every command, not into a debug log.
    """
    path = getattr(args, "audit_log", None)
    if not path or not getattr(args, "audit", True):
        return
    record = {"schema": AUDIT_SCHEMA,
              "ts": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
              "host": os.uname().nodename,
              "event": event}
    for key in sorted(fields):
        record[key] = fields[key]
    line = json.dumps(record, separators=(",", ":"), sort_keys=True) + "\n"
    try:
        directory = os.path.dirname(path)
        if directory and not os.path.isdir(directory):
            os.makedirs(directory)
        with open(path, "a") as handle:
            handle.write(line)
            handle.flush()
            os.fsync(handle.fileno())
    except (OSError, IOError) as exc:
        sys.stderr.write("warning: audit log %s not written (%s); state change stands\n" % (path, exc))


def bypass_state(path, now=None):
    """E5: read the bypass file and return its state, or None when no bypass is active.

    An expired bypass is reported as inactive *and* left in place so the next write records that it
    lapsed rather than silently vanishing; `cmd_expire` is what clears it. A malformed file is an
    error rather than a silent "off", because silently losing a bypass someone deliberately set is how
    an incident becomes a mystery.
    """
    if not path or not os.path.exists(path):
        return None
    with open(path) as handle:
        try:
            state = json.load(handle)
        except ValueError as exc:
            raise Error("bypass file %s is not valid JSON: %s" % (path, exc))
    if not isinstance(state, dict) or state.get("schema") != BYPASS_SCHEMA:
        raise Error("bypass file %s has an unsupported schema (expected %d)" % (path, BYPASS_SCHEMA))
    if state.get("state") not in ("on", "off"):
        raise Error("bypass file %s has unknown state %r" % (path, state.get("state")))
    if state.get("state") == "off":
        return None
    expires = state.get("expires_epoch")
    if expires is not None and (now if now is not None else time.time()) >= float(expires):
        return dict(state, expired=True)
    return dict(state, expired=False)


def write_bypass(path, state):
    """Persist the bypass atomically so a reader never sees a half-written intent.

    The parent directory is created on demand: on a host where the controller was installed but never
    used, `/var/lib/adaptive-tarpit` may not exist, and an emergency bypass that fails because a
    directory is missing is not an emergency bypass.
    """
    directory = os.path.dirname(path)
    if directory and not os.path.isdir(directory):
        try:
            os.makedirs(directory)
        except (OSError, IOError) as exc:
            raise Error("cannot create bypass directory %s: %s" % (directory, exc))
    try:
        write_atomic(path, json.dumps(state, indent=1, sort_keys=True) + "\n")
    except (OSError, IOError) as exc:
        raise Error("cannot write bypass file %s: %s" % (path, exc))


def one_line(text):
    """Collapse a free-text field to a single line.

    The bypass reason is written into the rendered map as a comment. A newline in it ends the
    comment, and whatever follows is read as map data - so a reason containing `\n0.0.0.0/0 0` put
    the whole estate into bypass. Free text that reaches a line-oriented artifact is quoted or
    flattened; there is no third option.
    """
    return " ".join(str(text).split())


def render_map(leases, allowlist, max_tarpit=DEFAULT_MAX_TARPIT, bypass=None):
    """
    Build the Apache txt: map body.

    PT-04 - the three values are three *different* enforcement actions in the vhost:
      0 = serve normally (allowlisted),
      1 = proxy to the tarpit (the expensive, deliberate waste of attacker time),
      2 = over quota: a cheap local refusal, never a tarpit stream, never the real site.
    `max_tarpit` caps how many addresses may hold a value-1 slot; the excess is served
    value 2 so a mass-ban event cannot allocate unbounded backend capacity. Allowlisted
    IPs render as 0 rather than being omitted, so an allowlist entry stays auditable.
    """
    lines = [
        "%s at %s - do not edit by hand." % (GENERATED_MARKER, time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())),
        "# source of truth: the controller store; this file is a build artifact.",
    ]
    if bypass:
        # E5: the bypass is stated in the artifact itself, so anyone reading the map - or diffing it
        # after an incident - can see enforcement was off and until when, without querying the store.
        expires = bypass.get("expires_epoch")
        expires_iso = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(float(expires))) if expires else "never"
        lines.append("# E5 BYPASS ACTIVE since %s, expires %s (expired=%s): %s" % (
            bypass.get("set_at", "unknown"), expires_iso,
            "yes" if bypass.get("expired") else "no", one_line(bypass.get("reason", ""))))
        lines.append("# every address renders 0 (serve normally) while the bypass is active.")
        # Every address renders 0 while the bypass is active - that is the point of the bypass, and
        # the `or True` that used to sit in this comprehension was the same statement written so it
        # read like a filter that someone had left half-finished. Say it once, plainly.
        return "\n".join(lines + ["%s 0" % lease["ip"] for lease in leases]) + "\n"
    quota_note = 0
    for lease in leases:
        if lease["ip"] in allowlist:
            value = 0
        elif max_tarpit and quota_note >= max_tarpit:
            value = 2
        else:
            value = 1
            quota_note += 1
        lines.append("%s %d" % (lease["ip"], value))
    return "\n".join(lines) + "\n"


def read_map_values(path):
    """Parse an existing map file into {ip: value} so we can diff and guard."""
    if not os.path.exists(path):
        return {}
    existing = {}
    with open(path) as handle:
        for line in handle:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            match = MAP_LINE.match(line)
            if not match:
                raise Error("existing map %s has an unparseable line: %r - refusing to overwrite" % (path, line))
            existing[match.group(1)] = match.group(2)
    return existing


def is_generated(path):
    """True if the file was produced by this controller (not hand-written or legacy)."""
    if not os.path.exists(path):
        return False
    with open(path) as handle:
        return handle.readline().startswith(GENERATED_MARKER)


def write_render_stamp(map_path, moment=None):
    """Record when the controller last rendered `map_path`, whether or not the content changed.

    PTN-14: the map encodes one value per address and no per-entry expiry, and a stable lease set is
    not rewritten, so the file's own mtime freezes while the controller is healthy. A consumer that
    only has the map cannot tell "nothing changed" from "the controller died", and holds every
    quarantine in the file forever. The stamp answers the question the map cannot: when did the
    controller last confirm this state.
    """
    moment = int(time.time()) if moment is None else int(moment)
    body = "\n".join([
        "# fleet-filter render stamp - do not edit by hand.",
        "rendered_at=%d" % moment,
        "rendered_at_iso=%s" % time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(moment)),
        "map=%s" % os.path.abspath(map_path),
        "",
    ])
    write_atomic(map_path + STAMP_SUFFIX, body)


def read_render_stamp(map_path):
    """Return the epoch recorded in a map's render stamp, or None when it is absent or unparseable."""
    stamp = "%s%s" % (map_path, STAMP_SUFFIX)
    if not os.path.exists(stamp):
        return None
    try:
        with open(stamp) as handle:
            for line in handle:
                line = line.strip()
                if line.startswith("rendered_at="):
                    return int(line.split("=", 1)[1])
    except (ValueError, OSError):
        return None
    return None


def write_atomic(path, content):
    """Write the map with tmp + fsync + rename so a reader never sees a partial file.

    Apache's `txt:` map reader can open the file at any moment; a truncated read would
    serve a quarantined IP as normal. `fsync` before the rename is what makes the rename
    durable rather than merely atomic at the filesystem level.
    """
    directory = os.path.dirname(os.path.abspath(path))
    handle, tmp = tempfile.mkstemp(dir=directory, prefix=".tarpit-ips.", suffix=".tmp")
    try:
        with os.fdopen(handle, "w") as out:
            out.write(content)
            out.flush()
            os.fsync(out.fileno())
        os.chmod(tmp, 0o644)
        os.replace(tmp, path)          # atomic: Apache's txt: reader never sees a partial file
    except BaseException:
        if os.path.exists(tmp):
            os.unlink(tmp)
        raise


def read_map_values_from_body(body):
    """Parse a rendered map body into `{ip: value}`.

    Raises on an unparseable line instead of skipping it: a silently dropped line is a
    silently un-quarantined address, which is the failure mode this whole path exists to
    avoid. Only used on bodies we generated (see `is_generated`).
    """
    out = {}
    for line in body.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        match = MAP_LINE.match(line)
        if not match:
            raise Error("generated map body is unparseable: %r" % line)
        out[match.group(1)] = match.group(2)
    return out


def cmd_claim(args):
    """`claim` subcommand: record verdicts for one or more IPs, then optionally render.

    Allowlisted addresses are reported and skipped rather than leased - leasing one would
    only ever render as 0 and would add permanent noise to the audit trail.

    Every address is validated before any write happens. Validating inside the write loop
    let `claim 10.0.0.1 999.0.0.1` store the good address and then fail on the bad one: a
    non-zero exit that had still mutated state, which is the one thing a caller cannot
    recover from by retrying the same command.
    """
    store = Store(args.db)
    if store.migrated_from:
        sys.stderr.write("note: migrated v1 store (%s)\n" % store.migrated_from)
    if not args.author:
        args.author = os.uname().nodename
    allowlist = load_allowlist(args.allowlist)
    for ip in args.ip:
        validate_ip(ip)
    results = []
    for ip in args.ip:
        if ip in allowlist:
            # Never create a lease for an allowlisted address; the map would only ever
            # render it as 0, and the lease would be noise in the audit trail.
            results.append((ip, "allowlisted", None))
            continue
        # H4: an explicit --ttl wins. Otherwise the ladder picks the length from how often this
        # address has been claimed before and names the reason, so the audit line can say whether
        # the lease is 15m, 30m, 60m, or why the address was released instead of leased.
        decision = None
        ttl = args.ttl
        if ttl is None:
            prior = store.ladder_state(ip)
            decision = ladder_mod.resolve(0 if prior is None else prior["claims"],
                                          args.verdict,
                                          getattr(args, "ladder_terminal", ladder_mod.DEFAULT_TERMINAL))
            ttl = decision["ttl"]
        if decision is not None and decision["action"] == "release":
            store.revoke(ip)
            result = "released"
        else:
            result = store.claim(ip, args.verdict, args.source, args.author, ttl)
        if decision is not None:
            store.record_ladder(ip, decision["rung"])
        results.append((ip, result, decision))
    for ip, result, decision in results:
        print("%-16s %s" % (ip, result))
        # One audit line per address, including the refusals: Wazuh needs to see the allowlisted
        # suppression too, or the feed silently understates what the controller decided.
        if args.ttl is not None:
            effective_ttl = args.ttl
        elif decision is not None:
            effective_ttl = decision["ttl"]
        else:
            effective_ttl = DEFAULT_TTL.get(args.verdict)
        fields = {}
        if decision is not None:
            fields = {"ladder_rung": decision["rung"], "ladder_reason": decision["reason_code"],
                      "prior_claims": decision["prior_claims"]}
        emit_audit(args, "claim", ip=ip, result=result, verdict=args.verdict,
                   source=args.source, author=args.author or os.uname().nodename,
                   ttl=effective_ttl, **fields)
    if args.render:
        do_render(store, args)
    return 0


def cmd_revoke(args):
    """`revoke` subcommand: remove one source's claim (--claim-key) or every claim for the
    address. Returns 1 when there was nothing to revoke, so a script can detect a no-op."""
    store = Store(args.db)
    if not store.revoke(args.ip, args.claim_key):
        print("no lease for %s" % args.ip)
        return 1
    print("revoked %s%s" % (args.ip, (" claim %s" % args.claim_key) if args.claim_key else " (all claims)"))
    emit_audit(args, "revoke", ip=args.ip,
               claim_key=args.claim_key or "*", scope="claim" if args.claim_key else "all")
    if args.render:
        do_render(store, args)
    return 0


def cmd_list(args):
    """`list` subcommand: print active leases folded to one row per address, or --json.

    Folding is deliberate (PT-05): the operator needs the effective verdict per address,
    and the `CLAIMS` column shows how many independent sources contributed to it.
    """
    store = Store(args.db, readonly=True)
    if not store.authoritative:
        print("(no store at %s)" % args.db)
        return 0
    leases = store.active()
    if args.json:
        print(json.dumps(leases, indent=2))
        return 0
    if not leases:
        print("(no active leases)")
        return 0
    print("%-16s %-9s %-22s %-6s %-10s %s" % ("IP", "VERDICT", "SOURCE", "TTL_LEFT", "CLAIMS", "AUTHOR"))
    for lease in leases:
        print("%-16s %-9s %-22s %-6s %-10s %s" % (
            lease["ip"], lease["verdict"], lease["source"] or "-",
            "%ds" % (lease["expires_at"] - now()), lease["claims"], lease["author"] or "local"))
    return 0


def cmd_bypass(args):
    """E5: turn the emergency bypass on or off, then re-render.

    The bypass is the answer to "enforcement is causing harm and I need it off in one command, now".
    It must not depend on Wazuh (no verdicts are consulted), on the responder (an all-zero map means
    Apache never proxies to the tarpit, so a dead responder stops mattering), or on the store being
    healthy (the intent lives in a JSON file). A TTL is required so the state cannot be forgotten:
    enforcement silently off is its own outage, and an expiring bypass converts "someone forgot to turn
    it back off" into a timed event with a recorded reason.
    """
    path = args.bypass_file
    if args.state == "off":
        if not os.path.exists(path):
            print("no bypass in effect (%s does not exist)" % path)
            return 0
        previous = bypass_state(path) or {"state": "off", "set_at": "unknown"}
        write_bypass(path, {"schema": BYPASS_SCHEMA, "state": "off",
                           "previous_set_at": previous.get("set_at"),
                           "cleared_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())})
        print("bypass cleared")
        emit_audit(args, "bypass", state="off",
                   actor=getattr(args, "actor", "") or os.environ.get("USER") or "unknown",
                   previous_set_at=previous.get("set_at"),
                   cleared_at=time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()))
        if args.render:
            do_render(Store(args.db), args, authoritative=True)
        return 0

    if args.ttl is None:
        raise Error("`bypass on` requires --ttl SECONDS so the bypass cannot be forgotten")
    state = {
        "schema": BYPASS_SCHEMA,
        "state": "on",
        "set_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "expires_epoch": int(time.time()) + int(args.ttl),
        "reason": args.reason or "unspecified",
        "actor": args.actor or os.environ.get("USER") or "unknown",
    }
    write_bypass(path, state)
    emit_audit(args, "bypass", state="on", ttl=int(args.ttl), reason=args.reason or "unspecified",
               actor=state["actor"], expires_at=time.strftime("%Y-%m-%dT%H:%M:%SZ",
                                                              time.gmtime(state["expires_epoch"])))
    print("bypass ON for %ds (until %s) - %s" % (
        int(args.ttl),
        time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(state["expires_epoch"])),
        state["reason"]))
    if args.render:
        do_render(Store(args.db), args, authoritative=True)
    return 0


def cmd_expire(args):
    """`expire` subcommand: purge expired claims, then render.

    Passes `authoritative=True` explicitly - a successful read that yields nothing is real
    state and must be written, which is the entire point of expiry (PT-01).
    """
    # E5: an expired bypass is cleared here rather than at read time, so the clearing is part of the
    # timed, logged run instead of an invisible side effect of whoever happens to read the file.
    bypass_path = getattr(args, "bypass_file", DEFAULT_BYPASS)
    active = bypass_state(bypass_path) if bypass_path else None
    if active and active.get("expired"):
        write_bypass(bypass_path, {"schema": BYPASS_SCHEMA, "state": "off",
                                   "previous_set_at": active.get("set_at"),
                                   "cleared_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
                                   "cleared_reason": "ttl expired"})
        print("E5 bypass expired (set %s) - enforcement restored" % active.get("set_at"))
    store = Store(args.db)
    expiring = store.expired_ips()
    removed = store.purge_expired()
    print("purged %d expired claim(s)" % removed)
    if removed:
        emit_audit(args, "expire", removed=removed, addresses=expiring)
    if args.render:
        # PT-01: the store was read successfully, so an empty result is authoritative and
        # must be rendered - that is the whole point of expiry.
        do_render(store, args, authoritative=True)
    return 0


def cmd_verify(args):
    """PT-11 - health check: is the on-disk map what the store says it should be?

    Catches a deleted, corrupted, hand-edited or stale map between timer runs. Usable as
    a systemd `ExecStartPost=` or a monitoring check; exits 1 on any drift.
    """
    store = Store(args.db, readonly=True)
    if not store.authoritative:
        raise Error("no claim store at %s - nothing to verify against" % args.db)
    if args.max_tarpit is None:
        # reproduce the parameters the map was actually rendered with
        stored = store.get_meta("last_max_tarpit", str(DEFAULT_MAX_TARPIT))
        try:
            max_tarpit = int(stored)
        except (TypeError, ValueError):
            max_tarpit = DEFAULT_MAX_TARPIT
    else:
        max_tarpit = args.max_tarpit
    # E5: while a bypass is active the correct map is the bypassed one, so verify must reproduce
    # the same view render does - otherwise the health check cries wolf during an incident.
    expected_body = render_map(store.active(), load_allowlist(args.allowlist), max_tarpit,
                               bypass=bypass_state(getattr(args, "bypass_file", DEFAULT_BYPASS)))
    expected = read_map_values_from_body(expected_body)
    if not os.path.exists(args.map):
        raise Error("map %s is missing but the store has %d entries" % (args.map, len(expected)))
    if not is_generated(args.map):
        raise Error("map %s is not a generated artifact (hand-edited?)" % args.map)
    actual = read_map_values(args.map)
    if actual != expected:
        missing = sorted(set(expected) - set(actual))
        extra = sorted(set(actual) - set(expected))
        changed = sorted(ip for ip in set(actual) & set(expected) if actual[ip] != expected[ip])
        raise Error("map %s drifted from the store: missing=%s extra=%s changed=%s"
                    % (args.map, missing or "-", extra or "-", changed or "-"))
    if not args.quiet:
        print("ok: %s matches the store (%d entries)" % (args.map, len(actual)))
    return 0


def spool_files(spool):
    """Return the queued claim files in `spool`, oldest submission first ([] if no spool).

    Sorting by filename reconstructs submission order, because producers name files with the
    observation epoch. Order is not cosmetic: a batch holding both a `suspect` and a
    `confirmed` claim for one address must apply the weaker first, or PT-05's monotonic
    promotion rule would treat the stronger claim as a downgrade and refuse it.
    `*.tmp` files are skipped - that is the staging name producers use before the atomic
    rename, so reading one would consume a half-written claim.

    R2: entries are checked with `lstat`, so a symlink is not ingested even though `isfile`
    would follow it and say yes. A symlink in a directory any local account can write is how a
    "claim file" ends up pointing at /etc/shadow: the consumer opens the link, not the entry,
    and reads whatever the link target holds.
    """
    if not os.path.isdir(spool):
        return []
    found = []
    for name in sorted(os.listdir(spool)):
        path = os.path.join(spool, name)
        if not name.endswith(".json") or name.endswith(".tmp"):
            continue
        try:
            mode = os.lstat(path).st_mode
        except OSError:
            # Vanished between listdir and lstat: another consumer won the race, nothing to read.
            continue
        if stat.S_ISREG(mode):
            found.append(path)
        else:
            sys.stderr.write("skipped %s: not a regular file\n" % path)
    return found


def parse_spool_claim(raw):
    """Validate one queued claim object and normalise it for `Store.claim`.

    The producer supplies `subject_ip` and `verdict`; everything else is optional and
    defaulted so a producer cannot accidentally mint a new claim identity per request
    (`claim_key` falls back to `source`, which is what makes repeat observations from the
    same source extend one lease instead of creating N rows). `ttl` stays None when the
    producer omits it, which is the signal to use the verdict's policy TTL - the producer
    observes, the controller decides how long a verdict lasts.
    """
    if not isinstance(raw, dict):
        raise Error("claim must be a JSON object, got %s" % type(raw).__name__)
    # R1: the record schema is versioned and validated. A missing field is the legacy v1
    # responder format (deployed before the field existed), 1 is current, and anything else is
    # refused. Refusing an unknown version is what stops a future producer from writing a record
    # this controller half-understands: the file is quarantined with its bytes intact instead of
    # being parsed with the old meaning.
    version = raw.get("schema_version", 1)
    if version != SCHEMA_VERSION:
        raise Error("unsupported schema_version %r (this controller reads %d)" % (version, SCHEMA_VERSION))
    ip = raw.get("subject_ip") or raw.get("ip")
    if not ip:
        raise Error("claim is missing subject_ip")
    validate_ip(ip)
    verdict = raw.get("verdict") or "suspect"
    if verdict not in DEFAULT_TTL:
        raise Error("verdict must be one of %s" % ", ".join(sorted(DEFAULT_TTL)))
    source = raw.get("source") or "spool"
    return {
        "ip": ip,
        "verdict": verdict,
        "source": source,
        "author": raw.get("author") or source,
        "ttl": raw.get("ttl"),
        "claim_key": raw.get("claim_key") or source,
    }


def cmd_drain_spool(args):
    """Fold queued claims from the spool directory into the store (Bundle L4, Bundle R).

    Producers that face the network must not hold SQLite write access, so they drop one JSON
    file per observation and this command moves those observations into the same claim table
    every other source uses. It is safe to run repeatedly, which is what lets the existing
    `adaptive-tarpit.timer` be the single scheduler for expiry, rendering, and now draining.

    Failure handling is deliberately asymmetric: a claim that validates is consumed (file
    removed once the row exists), while one that does not is moved to `failed/`. Deleting a
    malformed file loses the evidence; leaving it in place would block the queue and be
    retried on every timer run forever.
    """
    files = spool_files(args.spool)
    if not files and args.quiet:
        return 0
    if not files:
        print("ok: no queued claims in %s" % args.spool)
        return 0

    store = Store(args.db)
    if store.migrated_from:
        sys.stderr.write("note: migrated v1 store (%s)\n" % store.migrated_from)
    allowlist = load_allowlist(args.allowlist)

    filed = skipped = failed = 0
    for path in files:
        name = os.path.basename(path)
        file_failed = False
        try:
            with open(path) as handle:
                body = json.load(handle)
        except ValueError as exc:
            print("malformed  %s  %s" % (name, exc))
            failed += 1
            if not args.dry_run:
                _quarantine_spool_file(args.spool, path, "malformed")
                continue
            continue

        items = body if isinstance(body, list) else [body]
        for item in items:
            try:
                claim = parse_spool_claim(item)
            except Error as exc:
                print("invalid    %s  %s" % (name, exc))
                failed += 1
                file_failed = True
                continue
            if claim["ip"] in allowlist:
                # An allowlisted address must not acquire a lease from any source, and the
                # claim is still consumed: re-queueing it would fail the same way forever.
                print("allowlist  %-16s claim %s consumed without a lease" % (claim["ip"], claim["claim_key"]))
                skipped += 1
                continue
            if args.dry_run:
                print("dry-run    %-16s %s (%s)" % (claim["ip"], claim["verdict"], claim["claim_key"]))
                continue
            result = store.claim(
                claim["ip"], claim["verdict"], source=claim["source"],
                author=claim["author"], ttl=claim["ttl"], claim_key=claim["claim_key"],
            )
            print("%-10s %-16s %s (%s)" % (result, claim["ip"], claim["verdict"], claim["claim_key"]))
            filed += 1

        # Only consume the file when every claim in it was handled. A file with one good and
        # one bad claim keeps the good row AND stays queued, so the bad claim is still
        # visible instead of being silently dropped alongside its valid sibling.
        if not args.dry_run and not file_failed:
            os.remove(path)

    if args.render:
        do_render(store, args)
    if not args.quiet:
        print("summary: %d filed, %d allowlisted, %d failed (%d files)" % (filed, skipped, failed, len(files)))
    return 1 if failed and not args.dry_run else 0


def _quarantine_spool_file(spool, path, reason):
    """Move a bad claim file to `<spool>/failed/`, keeping the run's evidence intact.

    The destination name is prefixed with the epoch so two bad files from different runs do
    not overwrite each other, which matters because the only record of a malformed claim is
    the file itself.
    """
    failed_dir = os.path.join(spool, "failed")
    try:
        if not os.path.isdir(failed_dir):
            os.makedirs(failed_dir)
        os.rename(path, os.path.join(failed_dir, "%d-%s" % (int(now()), os.path.basename(path))))
    except OSError as exc:
        sys.stderr.write("could not quarantine %s: %s\n" % (path, exc))


def do_render(store, args, authoritative=None):
    """Render the map from the store.

    PT-01: the "refusing to write an empty map" guard applies only when the store read is
    NOT authoritative (a failed or partial state read, e.g. a fleet sync that returned
    nothing). A successfully read empty store is real state and renders an empty map; the
    old behaviour treated legitimate expiry as corruption and left the address in the map
    forever, which is exactly the failure the guard was meant to prevent.
    """
    leases = store.active()
    if authoritative is None:
        authoritative = store.authoritative
    allowlist = load_allowlist(args.allowlist)
    body = render_map(leases, allowlist, getattr(args, "max_tarpit", DEFAULT_MAX_TARPIT),
                    bypass=bypass_state(getattr(args, "bypass_file", DEFAULT_BYPASS)))

    if getattr(args, "dry_run", False):
        sys.stdout.write(body)
        return

    # E13/H6: refuse to clobber a file we did not generate. `verify` already refuses to audit a
    # hand-written map; render used to overwrite one silently, which destroys the evidence `verify`
    # would have flagged and the usual cause is someone editing the artifact instead the store.
    if os.path.exists(args.map) and os.path.getsize(args.map) > 0 and not is_generated(args.map):
        raise Error(
            "refusing to overwrite %s: it exists and is not a generated artifact (hand-edited? "
            "move it aside, or fix the store and let the timer render)" % args.map
        )
    existing = read_map_values(args.map)
    new = read_map_values_from_body(body)
    if existing and not new and not authoritative and not getattr(args, "allow_empty", False):
        raise Error(
            "refusing to write an empty map over one that had %d entries; "
            "the store read was not authoritative (use --allow-empty to override)" % len(existing)
        )
    if existing == new and is_generated(args.map):
        # Idempotent: no rewrite, so no spurious mtime change for Apache's 60s cache. The stamp still
        # advances (PTN-14), because "nothing changed" and "nobody is rendering" must not look identical.
        write_render_stamp(args.map)
        return  # idempotent: no rewrite, so no spurious mtime change for Apache's 60s cache
    write_atomic(args.map, body)
    write_render_stamp(args.map)
    store.set_meta("last_max_tarpit", getattr(args, "max_tarpit", DEFAULT_MAX_TARPIT))
    print("rendered %d entries -> %s" % (len(new), args.map))


def _add_render_options(parser, with_render=True, with_dry_run=False,
                        with_max_tarpit=True, with_allow_empty=True):
    """PT-04: every path that can render must expose the same quota/empty controls,
    otherwise a cap set on one invocation is silently undone by the next one."""
    if with_render:
        parser.add_argument("--render", action="store_true", help="render the map after the change")
    if with_dry_run:
        parser.add_argument("--dry-run", action="store_true",
                            help="print the rendered map instead of writing it")
    if with_allow_empty:
        parser.add_argument("--allow-empty", action="store_true",
                            help="permit rendering a map with no entries (legacy flag; the "
                                 "guard now only fires when the store read is not authoritative)")
    if with_max_tarpit:
        parser.add_argument("--max-tarpit", type=int, default=DEFAULT_MAX_TARPIT,
                            help="cap on value-1 entries; excess becomes value 2 (0 = unlimited)")


def build_parser():
    """Build the CLI parser.

    The global options (`--db`, `--map`, `--allowlist`) are declared on the top-level
    parser *before* the subcommands, because argparse only accepts them in that position -
    putting them on a subparser broke `claim --render` invocations that passed them after
    the subcommand name.
    """
    parser = argparse.ArgumentParser(prog="adaptive-tarpit", description=__doc__.strip().split("\n")[1])
    parser.add_argument("--db", default=DEFAULT_DB, help="claim store path (default %s)" % DEFAULT_DB)
    parser.add_argument("--map", dest="map", default=DEFAULT_MAP, help="Apache map file to render")
    parser.add_argument("--allowlist", default=DEFAULT_ALLOWLIST, help="local allowlist file")
    parser.add_argument("--bypass-file", default=DEFAULT_BYPASS,
                        help="E5 emergency bypass file (default %s)" % DEFAULT_BYPASS)
    parser.add_argument("--audit-log", default=DEFAULT_AUDIT_LOG,
                        help="E13 structured audit log to append to (default %s)" % DEFAULT_AUDIT_LOG)
    parser.add_argument("--no-audit", dest="audit", action="store_false",
                        help="suppress the E13 audit line (for tests and dry runs)")
    sub = parser.add_subparsers(dest="cmd")

    p = sub.add_parser("claim", help="record a verdict for one or more IPs")
    p.add_argument("ip", nargs="+")
    p.add_argument("--verdict", required=True, choices=sorted(DEFAULT_TTL))
    p.add_argument("--source", help="signature id or rule id, never a raw log line "
                   "(it also identifies the claim, so the same IP can hold several opinions)")
    p.add_argument("--author", help="host or subsystem making the claim (default: this host)")
    p.add_argument("--ttl", type=int, help="override the verdict's default TTL (seconds)")
    p.add_argument("--ladder-terminal", default=ladder_mod.DEFAULT_TERMINAL,
                   choices=sorted(ladder_mod.TERMINAL_MODES),
                   help="H4: what an exhausted escalation ladder does to a suspect address "
                        "(default: %s)" % ladder_mod.DEFAULT_TERMINAL)
    _add_render_options(p)
    p.set_defaults(func=cmd_claim)

    p = sub.add_parser("revoke", help="remove a lease (one claim, or all claims for the IP)")
    p.add_argument("ip")
    p.add_argument("--claim-key", help="remove only this source's claim; the other sources keep theirs")
    _add_render_options(p)
    p.set_defaults(func=cmd_revoke)

    p = sub.add_parser("list", help="show active leases (one row per address, all claims folded)")
    p.add_argument("--json", action="store_true")
    p.set_defaults(func=cmd_list)

    p = sub.add_parser("expire", help="purge expired claims")
    _add_render_options(p)
    p.set_defaults(func=cmd_expire)

    p = sub.add_parser("drain-spool",
                       help="fold queued claims from the spool directory into the store")
    p.add_argument("--spool", default=DEFAULT_SPOOL,
                   help="claim spool directory written by the responder/gateway (default %s)" % DEFAULT_SPOOL)
    p.add_argument("--quiet", action="store_true", help="only print a summary line")
    # with_dry_run=True: draining is the one operation where "show me, do not consume" is
    # the normal first run, because a drain deletes the producer's files on success.
    _add_render_options(p, with_dry_run=True)
    p.set_defaults(func=cmd_drain_spool)

    p = sub.add_parser("ingest", help="consume a verdict payload (Wazuh AR JSON / fleet claim) and record it")
    p.add_argument("--file", default="-", help="JSON payload file, or - for stdin (default -)")
    p.add_argument("--verdict", choices=sorted(DEFAULT_TTL),
                   help="force a verdict instead of deriving it from the rule id")
    p.add_argument("--confirm-rule", action="append",
                   help="rule id whose contract authorises a confirmed verdict (repeatable); "
                        "default %s" % ",".join(DEFAULT_CONFIRM_RULES))
    p.add_argument("--confirm-by-level", action="store_true",
                   help="legacy behaviour: allow rule level to decide confirmed vs suspect")
    p.add_argument("--confirm-level", type=int, default=12,
                   help="level used with --confirm-by-level (default 12)")
    p.add_argument("--on-delete", choices=("ignore", "revoke"), default="ignore",
                   help="what to do with an active-response delete/unban event (default ignore)")
    p.add_argument("--ttl", type=int, help="override the derived TTL (seconds)")
    p.add_argument("--author", help="author recorded on the claim (default: derived from "
                   "--source, else 'wazuh')")
    p.add_argument("--source", help="provenance recorded on the claim, overriding the value derived "
                   "from the payload (e.g. wazuh-rule-30101). Set this for any source that is not a "
                   "Wazuh alert, e.g. --source fail2ban-apache-fleet-filter")
    p.add_argument("--expect-agent-id", help="refuse alerts about a different Wazuh agent id")
    p.add_argument("--own-log", action="append", default=None,
                   help="a log path this controller generates (repeatable); alerts from it are skipped. "
                        "Default: %s" % ", ".join(DEFAULT_OWN_LOGS))
    _add_render_options(p, with_dry_run=True)
    p.set_defaults(func=cmd_ingest)

    p = sub.add_parser("render", help="regenerate the Apache map from the store")
    _add_render_options(p, with_render=False, with_dry_run=True)
    p.set_defaults(func=cmd_render)

    p = sub.add_parser("bypass", help="E5: emergency bypass - render every address as 0 for a fixed TTL")
    p.add_argument("state", choices=("on", "off"), help="turn the bypass on or off")
    p.add_argument("--ttl", type=int, default=None,
                   help="seconds to keep the bypass on (required for `on`; the timer clears it at expiry)")
    p.add_argument("--reason", default="", help="why enforcement is off (recorded in the map header)")
    p.add_argument("--actor", default="", help="who set it (default: $USER)")
    p.add_argument("--no-render", dest="render", action="store_false",
                   help="record the bypass without re-rendering the map")
    p.set_defaults(func=cmd_bypass, render=True)

    p = sub.add_parser("verify", help="PT-11 health check: does the on-disk map match the store?")
    p.add_argument("--quiet", action="store_true")
    p.add_argument("--max-tarpit", type=int, default=None,
                   help="override the quota used for the comparison (default: the value the "
                        "map was last rendered with)")
    p.set_defaults(func=cmd_verify)
    return parser


def cmd_render(args):
    """`render` subcommand: regenerate the Apache map from the store without changing state."""
    store = Store(args.db)
    do_render(store, args)
    return 0


def main(argv=None):
    """Entry point: parse, dispatch to the subcommand, and turn `Error` into exit 1.

    Every expected failure is an `Error`; anything else propagates as a traceback, which is
    how a genuine bug gets distinguished from a validated refusal in the logs.
    """
    parser = build_parser()
    args = parser.parse_args(argv)
    if not getattr(args, "func", None):
        parser.print_help()
        return 2
    try:
        return args.func(args)
    except Error as exc:
        sys.stderr.write("error: %s\n" % exc)
        return 1


if __name__ == "__main__":
    sys.exit(main())
