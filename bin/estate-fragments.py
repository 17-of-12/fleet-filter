#!/usr/bin/env python3
"""Turn a container inventory into per-host estate fragments for the CVE triage.

The triage is only as good as `config/estate.yaml`, and that file was hand-written - which makes it
the weakest link in the whole pipeline: a wrong version means a CVE is either missed or worked on
for nothing. The fleet already has `bin/container-inventory.py`, which reads container and image
state off each host over SSH without changing anything. This turns that JSON into the fragments the
triage merges.

Why fragments rather than one regenerated file: a person keeps the global file for things that are
not containers (a host's OpenSSL, a package Apache), and the generated fragments fill in the
containers. Regenerating one file would silently delete the hand-written entries on the next run.

Mapping is explicit, because guessing a CPE vendor from an image name is how "httpd" becomes "apache
foundation" in one record and "apache" in another. Only the products this pipeline can reason about
are emitted; an unknown image is reported and skipped, never invented.

Usage:
    container-inventory.py --hosts ff-apache01,ff-apache02 --json /tmp/inv.json
    estate-fragments.py --inventory /tmp/inv.json --out-dir config/estate.d
"""

import argparse
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent

# image repository -> (CPE vendor, CPE product). The versions come from the tag.
IMAGE_PRODUCTS = {
    "httpd": ("apache", "httpd"),
    "php": ("php", "php"),
    "wordpress": ("wordpress", "wordpress"),
    "mariadb": ("mariadb", "mariadb"),
    "mysql": ("oracle", "mysql"),
    "nginx": ("nginx", "nginx"),
    "tomcat": ("apache", "tomcat"),
}

# Locally built images whose repository name does not say which product they are. These are the
# ones a sweep would otherwise drop silently, which is exactly the "we run it but never see its
# CVEs" failure the fragments exist to prevent.
IMAGE_ALIASES = {
    "ff-httpd": "httpd",
    "fleet-filter-apache": "httpd",
}

# Tags that are not versions. An image tagged `alpine` has no version to compare, and inventing one
# would put a fake number into a range check.
NON_VERSIONS = {"latest", "alpine", "stable", "mainline", "bookworm", "trixie", "slim", "fpm", "cli"}


def product_for(repository):
    """The mapping for a repository name, following the local-build aliases."""
    if repository in IMAGE_PRODUCTS:
        return IMAGE_PRODUCTS[repository]
    return IMAGE_PRODUCTS.get(IMAGE_ALIASES.get(repository, ""), None)


def split_image(reference):
    """Split `docker.io/library/php:8.4.26-fpm` into (repository, tag)."""
    without_digest = reference.split("@")[0]
    if ":" in without_digest.rsplit("/", 1)[-1]:
        repository, tag = without_digest.rsplit(":", 1)
    else:
        repository, tag = without_digest, ""
    repository = repository.rsplit("/", 1)[-1]
    return repository.lower(), tag


def version_from_tag(tag):
    """Pull the leading version out of a tag: `8.4.26-fpm` -> `8.4.26`, `alpine` -> None."""
    if not tag:
        return None
    head = tag.split("-")[0]
    if head.lower() in NON_VERSIONS:
        return None
    return head if re.match(r"^\d+(\.\d+)*$", head) else None


def products_for_host(host):
    """Every recognised product the host runs, with the versions seen in its images.

    Images are the source, containers add nothing a tag does not already say: a container is a tag
    plus a name, and the name is ours rather than the product's.
    """
    found = {}
    for image in host.get("images") or []:
        reference = image.get("repository") if isinstance(image, dict) else str(image)
        if not reference:
            continue
        repository, tag = split_image(reference)
        mapping = product_for(repository)
        if not mapping:
            continue
        version = version_from_tag(tag)
        key = mapping
        entry = found.setdefault(key, {"vendor": key[0], "product": key[1], "running": []})
        if version and version not in entry["running"]:
            entry["running"].append(version)
    return found


def render_fragment(host, products):
    """A YAML fragment for one host: the header explains where the numbers came from."""
    lines = [
        "# Generated by bin/estate-fragments.py from bin/container-inventory.py - do not edit.",
        "# Host: %s" % host.get("fqdn", "unknown"),
        "# Versions come from image tags. A product tagged without a version is omitted rather than",
        "# guessed, because a made-up version is worse than a missing one in a range check.",
        "estate:",
    ]
    if not products:
        lines.append("  []")
        return "\n".join(lines) + "\n"
    for entry in sorted(products.values(), key=lambda item: (item["vendor"], item["product"])):
        versions = ", ".join('"%s"' % version for version in sorted(entry["running"]))
        lines += [
            "  - name: %s %s on %s" % (entry["vendor"], entry["product"], host.get("fqdn", "host")),
            "    vendor: %s" % entry["vendor"],
            "    product: %s" % entry["product"],
            "    running: [%s]" % versions,
        ]
    return "\n".join(lines) + "\n"


def main(argv=None):
    """Read the inventory, write one fragment per host, and report what could not be mapped."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--inventory", default="/tmp/inv.json", help="container-inventory.py --json output")
    parser.add_argument("--out-dir", default=str(REPO / "config" / "estate.d"))
    parser.add_argument("--dry-run", action="store_true", help="print instead of writing")
    args = parser.parse_args(argv)

    document = json.loads(Path(args.inventory).read_text())
    out = Path(args.out_dir)
    if not args.dry_run:
        out.mkdir(parents=True, exist_ok=True)

    written, unmapped = 0, set()
    for host in document.get("hosts", []):
        if host.get("ssh_error"):
            print("skipped %s: %s" % (host.get("fqdn"), host["ssh_error"]), file=sys.stderr)
            continue
        products = products_for_host(host)
        for image in host.get("images") or []:
            reference = image.get("repository") if isinstance(image, dict) else str(image)
            repository, _ = split_image(reference or "")
            if repository and product_for(repository) is None:
                unmapped.add(repository)
        fragment = render_fragment(host, products)
        if args.dry_run:
            print(fragment)
        else:
            target = out / ("%s.yaml" % host.get("fqdn", "unknown").replace("/", "_"))
            target.write_text(fragment)
            written += 1
        print("%-22s %d product(s)" % (host.get("fqdn", "?"), len(products)), file=sys.stderr)

    if unmapped:
        print("unmapped images (add to IMAGE_PRODUCTS if they belong in the estate): %s"
              % ", ".join(sorted(unmapped)), file=sys.stderr)
    if not args.dry_run:
        print("wrote %d fragment(s) to %s" % (written, out), file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
